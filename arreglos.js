let lista = []
//push=>agrega un elemento al final del arreglo
lista.push("a")
console.log(lista)
//push=>agrega un elemento al final del arreglo
lista.push("b")
console.log(lista)
//unshift=>agrega un elemento al inicio del arreglo
lista.unshift("c")
console.log(lista)
//pop=>elmina el ultimo elemento del arreglo
lista.pop()
console.log(lista)
//shift=>elimina el primer elemento del arreglo
lista.shift()
console.log(lista)